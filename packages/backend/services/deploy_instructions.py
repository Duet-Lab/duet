def _deploy_skills(
    context_folder: Path,
    skills: list[str] | None,
    repos_path: Path | None,
    context_folders: dict[str, str],
    warnings: list[str],
    guard: _SymlinkGuard,
) -> dict:
    # Absent key → don't manage the skills dirs at all.
    if skills is None:
        return {
            "skills_deployed": [],
            "skills_pruned": [],
            "agents_skills_deployed": [],
            "agents_skills_pruned": [],
        }

    to_deploy: list[tuple[str, Path]] = []
    seen: dict[str, str] = {}
    for entry in skills:
        src = resolve_at_path(entry, repos_path, context_folders)
        if src is None:
            warnings.append(f"skills: invalid or unresolvable @-path: {entry}")
            continue
        if not src.is_dir():
            warnings.append(f"skills: not a directory: {entry} ({src})")
            continue
        if not (src / SKILL_MANIFEST).is_file():
            warnings.append(f"skills: missing {SKILL_MANIFEST}: {entry}")
            continue
        name = src.name
        if name == PRUNED_DIR:
            warnings.append(
                f"skills: reserved deploy-name '{PRUNED_DIR}': {entry}; skipping"
            )
            continue
        if name in seen:
            warnings.append(
                f"skills: deploy-name collision '{name}': {entry} would overwrite "
                f"{seen[name]}; skipping"
            )
            continue
        seen[name] = entry
        to_deploy.append((name, src, entry))

    # Two client targets for the same declared set: `.claude/skills/` (Claude
    # Code) and `.agents/skills/` (cross-client convention, read by Kimi Code).
    deployed, pruned = _deploy_and_prune_skills(
        context_folder / CLAUDE_DIR / SKILLS_SUBDIR, to_deploy, guard
    )
    agents_deployed, agents_pruned = _deploy_and_prune_skills(
        context_folder / AGENTS_DIR / SKILLS_SUBDIR, to_deploy, guard
    )

    return {
        "skills_deployed": deployed,
        "skills_pruned": pruned,
        "agents_skills_deployed": agents_deployed,
        "agents_skills_pruned": agents_pruned,
    }


def _deploy_and_prune_skills(
    target_root: Path, to_deploy: list[tuple[str, Path, str]], guard: _SymlinkGuard
) -> tuple[list[str], list[str]]:
    """Mirror the declared skill set into `target_root`, then prune.

    Prune: any `<target_root>/<x>` not in the declared set is removed, but
    backed up first (symmetric with the instructions `.bak`). Backup = move
    into the `.pruned/` holding area, replacing any earlier backup of the
    same name with the most recent removed state. `.pruned/` is never pruned.

    Symlinks are not followed (`_SymlinkGuard`): a symlinked target root
    leaves the whole target alone, a symlinked skill directory is neither
    mirrored into nor pruned, a skill that holds a symlink is not moved to
    `.pruned`, and a backup that holds a symlink is not replaced.
    """
    if guard.blocked(target_root):
        return [], []

    deployed: list[str] = []
    if to_deploy:
        target_root.mkdir(parents=True, exist_ok=True)
        for name, src, ref in to_deploy:
            if guard.blocked(target_root / name):
                continue
            _mirror_tree_bytes(src, target_root / name, ref, guard)
            deployed.append(name)

    pruned: list[str] = []
    if target_root.is_dir():
        keep = {name for name, _, _ in to_deploy}
        for child in sorted(target_root.iterdir()):
            if child.name == PRUNED_DIR:
                continue
            if child.is_symlink():
                guard.report(child)
                continue
            if child.is_dir() and child.name not in keep:
                # Moving the skill would carry a symlink inside it to a new
                # place, where a relative one points elsewhere: such a skill
                # stays where it is, whole.
                if guard.links_under(child):
                    continue
                backup_root = target_root / PRUNED_DIR
                dst = backup_root / child.name
                if guard.blocked(dst):
                    continue
                backup_root.mkdir(parents=True, exist_ok=True)
                if dst.exists() and not guard.rmtree(dst):
                    continue
                shutil.move(str(child), str(dst))
                pruned.append(child.name)

    return deployed, pruned


def _mirror_tree_bytes(
    src_dir: Path, dst_dir: Path, ref: str | None = None, guard: _SymlinkGuard | None = None
) -> None:
    """Mirror `src_dir` onto `dst_dir` as raw bytes (binary-safe), touching only
    what actually differs.

    `ref` is the declared `@`-path of the skill. When given, the root
    `SKILL.md` is written with the provenance banner inserted after its
    frontmatter (`_bannered_skill_manifest`); every other file is a byte copy.
    The read-only mode says "not yours"; the banner says whose it is.

    Deliberately incremental rather than rmtree-and-rebuild. These trees are
    materialized inside the user's Drive folder, where removing a directory
    means "moved to Drive trash" — and deploy runs on every window open, so an
    unconditional rebuild sent every deployed skill to the trash many times a
    day. Overwriting a file in place is a new Drive revision, not a deletion,
    so only entries the source genuinely dropped are ever unlinked.

    Skill trees are small (hundreds of KB), so the comparison reads whole files
    rather than trusting size+mtime — a git checkout rewrites mtimes on files
    whose content never changed, which would reintroduce the churn.

    Deployed files are read-only, like the other Duet-managed artifacts: the
    whole tree is ours (the prune pass below owns the directory), so a hand edit
    here would be silently reverted on the next window open — the source is the
    thing to edit. The executable bit is the one thing carried over from the
    source, because a skill may ship scripts meant to be run directly.

    Directories named in `SKILL_EXCLUDED_DIRS` are left out wherever they sit
    in the source. Pass 2 then treats a copy of them already in the
    destination as something the source dropped, so a tree deployed before
    the exclusion existed is cleaned on the next deploy.

    A symlink already in the destination is never replaced, written through or
    removed: `guard` reports it, and the source entries at or under its path
    are skipped. The caller checks `dst_dir` itself.
    """
    if guard is None:
        guard = _SymlinkGuard(dst_dir.parent, [])
    # Defense in depth: `_deploy_skills` validates the source, but the prune
    # pass below deletes inside the user's Drive folder. An unreadable or empty
    # source (unmounted repo, revoked permissions) must degrade to a no-op, not
    # to "remove everything". A source holding nothing but excluded material
    # counts as empty for the same reason.
    if not src_dir.is_dir():
        return
    entries = [
        p for p in sorted(src_dir.rglob("*"))
        if not _is_excluded(p.relative_to(src_dir), p.is_dir())
    ]
    if not entries:
        return

    dst_dir.mkdir(parents=True, exist_ok=True)
    linked = {_mirror_key(link.relative_to(dst_dir)) for link in guard.links_under(dst_dir)}

    def behind_link(rel: Path) -> bool:
        return any(_mirror_key(Path(*rel.parts[: i + 1])) in linked for i in range(len(rel.parts)))

    # Pass 1 — bring the destination up to the source.
    wanted: set[str] = set()
    for src in entries:
        rel = src.relative_to(src_dir)
        wanted.add(_mirror_key(rel))
        if behind_link(rel):
            continue
        out = dst_dir / rel
        if src.is_dir():
            if out.is_symlink() or out.is_file():
                out.unlink()
            out.mkdir(parents=True, exist_ok=True)
        elif src.is_file():
            # A directory where the source now has a file is removed only when
            # it holds no symlink; otherwise it stays, and so does the file's
            # old shape.
            if out.is_dir() and not out.is_symlink() and not guard.rmtree(out):
                continue
            out.parent.mkdir(parents=True, exist_ok=True)
            executable = bool(src.stat().st_mode & stat.S_IXUSR)
            data = src.read_bytes()
            if ref is not None and rel == Path(SKILL_MANIFEST):
                data = _bannered_skill_manifest(data, ref)
            _write_if_changed(out, data, mode=0o555 if executable else 0o444)

    # Pass 2 — drop what the source no longer has. Deepest paths first, so a
    # directory is emptied before it is removed, over a listing materialized up
    # front because the walk mutates the tree it is walking. The walk does not
    # descend into symlinks, and a symlink, or a directory holding one, stays.
    present: list[Path] = []
    for dirpath, dirnames, filenames in os.walk(dst_dir, followlinks=False):
        present += [Path(dirpath) / name for name in dirnames + filenames]
    for stale in sorted(present, reverse=True):
        key = _mirror_key(stale.relative_to(dst_dir))
        if key in wanted or key in linked or stale.is_symlink():
            continue
        if stale.is_dir():
            guard.rmtree(stale)
        else:
            stale.unlink(missing_ok=True)


def _is_excluded(rel: Path, is_dir: bool) -> bool:
    """Whether a source path lies inside an excluded directory, or is one.

    Only directory names count. A plain file that happens to be called
    `tests` is still copied, so the last part is checked only when the path
    is a directory; every earlier part is a directory by construction.
    """
    dirs = rel.parts if is_dir else rel.parts[:-1]
    return any(part in SKILL_EXCLUDED_DIRS for part in dirs)


def _bannered_skill_manifest(data: bytes, ref: str) -> bytes:
    """Insert the provenance banner into a `SKILL.md` body.

    The banner goes right after the closing `---` of the frontmatter, so the
    client still parses `name` / `description` from the top of the file; a
    manifest without frontmatter gets the banner as its first line. A source
    that is not valid UTF-8 is copied untouched — the banner is a courtesy,
    never a reason to fail the deploy.
    """
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError:
        return data
    banner = _banner(ref)
    if text.startswith("---\n"):
        end = text.find("\n---\n", 4)
        if end != -1:
            head, body = text[: end + 5], text[end + 5 :]
            return f"{head}{banner}\n{body}".encode("utf-8")
    return f"{banner}\n\n{text}".encode("utf-8")


def _mirror_key(rel: Path) -> str:
    """Identity of a relative path for matching the two trees against each other.

    Compared under NFC + casefold because the destination is the user's Drive
    folder: on macOS it is case-insensitive and can hand back names in a
    different Unicode normal form than the source repo stores them in. The
    comparison is deliberately lax — a false match only leaves a stale file
    behind, while a false miss would delete a file we had just written.
    """
    return unicodedata.normalize("NFC", rel.as_posix()).casefold()


def _write_if_changed(target: Path, data: bytes, mode: int | None = None) -> None:
    """Write `data` to `target` only when it differs from what is already there.

    The write goes through a temp file in the same directory plus `os.replace`,
    so a reader never observes a half-written file and a read-only target needs
    no chmod (POSIX rename is governed by the directory). The temp name is
    randomized: a fixed suffix could collide with a real source filename.

    `mode` is the mode a file Duet owns outright must end up with. `None` means
    "take no position": an existing file keeps the mode it has, a new one gets
    0644. That is what the co-owned config files need (`.claude/settings.json`,
    `.codex/config.toml`) — there the mode is as much the user's as the keys we
    leave alone. The mode is always set explicitly, because `mkstemp` creates
    0600 and `os.replace` carries the temp file's mode over to the target, so a
    write that said nothing about the mode would narrow the file to 0600.
    """
    try:
        st: os.stat_result | None = target.stat()
        unchanged = st.st_size == len(data) and target.read_bytes() == data
    except OSError:
        st, unchanged = None, False  # missing or unreadable — write it

    if mode is None:
        mode = stat.S_IMODE(st.st_mode) if st is not None else 0o644

    # Right bytes, wrong mode: chmod in place, so the catch-up deploy over an
    # already up-to-date tree costs no Drive revision at all. Deliberately not
    # inside the `except OSError` above — a failing chmod must surface, not fall
    # through to rewriting a file whose content is already correct.
    if unchanged:
        if stat.S_IMODE(st.st_mode) != mode:
            os.chmod(target, mode)
        return

    fd, tmp_name = tempfile.mkstemp(dir=target.parent, prefix=".duet-", suffix=".tmp")
    try:
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, target)
    except BaseException:
        Path(tmp_name).unlink(missing_ok=True)
        raise


def _write_managed_file(target: Path, content: str, warnings: list[str]) -> None:
    """Write a Duet-managed instruction file read-only (0444).

    If a file already exists WITHOUT our generated banner, it was written by
    hand — silently back it up to ``<name>.bak`` (once) before overwriting.
    """
    if target.exists():
        try:
            existing = target.read_text(encoding="utf-8")
        except OSError:
            existing = ""
        if GENERATED_BANNER not in existing:
            backup = target.with_name(target.name + ".bak")
            if not backup.exists():
                try:
                    backup.write_bytes(target.read_bytes())
                except OSError as e:
                    warnings.append(f"system_prompt: backup failed for {target.name}: {e}")

    # Temp file + atomic replace through `_write_if_changed`: its temp name is
    # random and created exclusively, so an existing file or symlink can never
    # stand in for it. A fixed `<name>.tmp` could be a symlink, which the write
    # would follow and the replace would then move into the target's place.
    _write_if_changed(target, content.encode("utf-8"), mode=0o444)


